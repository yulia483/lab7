import re  
t = "Программирование на языке Python развивает алгоритмическое мышление."
# Извлекаем из текста все слова (только буквы и цифры) без знаков препинания
w = re.findall(r'\b\w+\b', t)
# Находим слово с максимальной длиной (key=len), если список слов не пуст
m = max(w, key=len) if w else ""

# Выводим найденное слово и количество символов в нём
print(f"Самое длинное слово: {m} (длина: {len(m)})")