t = "Привет, мир! Python — отличный язык."  # Исходный текст
c = {}  # Создаём пустой словарь для подсчёта: {'буква': количество}

# Проходим по каждому символу в строке
for x in t.lower():  # Переводим текст в нижний регистр
    if x.isalpha():  # Проверяем, что символ — это буква (игнорируем пробелы и знаки)
         #Берём текущее значение для буквы  и прибавляем 1
        c[x] = c.get(x, 0) + 1  

# Выводим буквы в алфавитном порядке и их количество
for k in sorted(c):
    print(f"{k}: {c[k]}")
